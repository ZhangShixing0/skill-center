const assert=require('node:assert/strict');
const M=require('../assets/dashboard/assets/task-match.js');
const B=require('../assets/dashboard/assets/task-brief.js');
const skills=['project-readme','web-ui-review','market-research'].map((name,i)=>({id:String(i),name,is_present:1}));
let count=0;const check=(name,run)=>{run();count++;};
for(const [query,expected] of [['完善项目 README','project-readme'],['检查网页手机布局','web-ui-review'],['研究市场和竞品','market-research']])check(query,()=>assert.equal(M.recommend(skills,query)[0]?.skill.name,expected));
check('empty',()=>assert.deepEqual(M.recommend(skills,''),[]));
check('unknown',()=>assert.deepEqual(M.recommend(skills,'火星瞬间传送'),[]));
check('removed',()=>assert.deepEqual(M.recommend([{id:'gone',name:'project-readme',is_present:0}],'README'),[]));
check('deduplicate',()=>assert.equal(M.recommend([...skills,{id:'copy',name:'plugin:project-readme',is_present:1}],'README').length,1));
check('negative clause',()=>assert.equal(M.recommend(skills,'不要网页检查，只要完善 README')[0].skill.name,'project-readme'));
check('unavailable route falls back to user skills',()=>assert.equal(M.recommend([{id:'custom',name:'custom-market-analysis',description:'市场研究与竞品对比',is_present:1}],'市场研究竞品对比')[0]?.skill.id,'custom'));
check('maximum three',()=>assert.ok(M.recommend(skills,'README 网页 市场').length<=3));
check('curated source',()=>assert.equal(B.guideFor(skills[0]).kind,'curated'));
check('generic source',()=>assert.equal(B.guideFor({name:'custom'}).kind,'generic'));
check('required goal',()=>assert.equal(B.build(skills[0],{}),''));
check('exact text',()=>assert.ok(B.build(skills[0],{goal:'先检查 <真实内容>'}).includes('先检查 <真实内容>')));
check('missing materials',()=>assert.ok(B.build(skills[0],{goal:'文档'}).includes('尚未提供')));
check('field bounds',()=>assert.equal(B.normalize({goal:'a'.repeat(2500)}).goal.length,2000));
console.log(`${count} task logic checks passed`);
